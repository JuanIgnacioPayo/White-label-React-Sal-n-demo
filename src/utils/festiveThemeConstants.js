export const getHolidaySuggestions = (name, templates = defaultTemplates) => {
  const lowerName = name.toLowerCase();
  
  const matchKey = Object.keys(templates).find(key => {
    if (key === 'generico') return false;
    const matchKeywords = templates[key].matchKeywords || [];
    return matchKeywords.some(kw => lowerName.includes(kw.toLowerCase()));
  });

  const selectedTemplate = matchKey ? templates[matchKey] : (templates.generico || defaultTemplates.generico);

  return {
    colors: selectedTemplate.colors || defaultTemplates.generico.colors,
    keyword: selectedTemplate.keyword || name.split(' ')[0] || 'Feriado',
    ideas: selectedTemplate.ideas || defaultTemplates.generico.ideas
  };
};

